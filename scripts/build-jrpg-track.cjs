// 将 Joth 的 CC0 原曲原字节打包；只分析琴音起音，生成画面落点。
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const input = path.join(root, 'assets/jrpg-piano.mp3');
const bytes = fs.readFileSync(input);
function decode(filter) {
  const result = spawnSync('ffmpeg', ['-v','error','-i', input,
    ...(filter ? ['-af', filter] : []), '-ar','22050','-ac','1','-f','f32le','pipe:1'],
  { maxBuffer: 16 * 1024 * 1024 });
  if (result.status !== 0) throw new Error(result.stderr.toString());
  return Float32Array.from({length: result.stdout.length / 4}, (_, i) => result.stdout.readFloatLE(i * 4));
}
const raw = decode();
const filtered = decode('highpass=f=650,lowpass=f=4800');
const rate = 22050, hop = 220, window = 441;
const energy = [];
for (let start = 0; start + window < filtered.length; start += hop) {
  let sum = 0;
  for (let j = 0; j < window; j++) sum += filtered[start+j] ** 2;
  energy.push(Math.sqrt(sum / window));
}
const novelty = energy.map((e, i) => Math.max(0, e - (energy[Math.max(0,i-3)] || 0)));
const maxNovelty = Math.max(...novelty);
const peaks = [];
for (let i = 2; i < novelty.length - 2; i++) {
  if (novelty[i] < maxNovelty * .075 || novelty[i] < Math.max(...novelty.slice(i-2,i+3))) continue;
  const at = Math.max(0, i * hop / rate);
  const previous = peaks.at(-1);
  if (previous && at - previous.at < .32) {
    if (novelty[i] > previous.strength) peaks[peaks.length-1] = { at, strength:novelty[i] };
  } else peaks.push({at, strength:novelty[i]});
}
const duration = raw.length / rate;
const visuals = peaks.map((peak, i) => {
  const strength = peak.strength / maxNovelty;
  const cross = i % 11 === 8;
  return {id:`piano-${i}`, at:peak.at, strength,
    visual:{kind:cross?'cross':'snowflake', size:cross?5.8:6.8+strength*1.6,
      flight:3.6+strength*.35, brightness:.85+strength*.15,
      turn:cross?.16:i%2?-.2:.2, x:.12+.76*((i*.381966+.3)%1)}};
});
const sections = ['初雪','窗灯','雪光','回环'].map((name,i) => ({name,
  from:i*duration/4, to:(i+1)*duration/4, intensity:[.45,.52,.58,.48][i]}));
const score = { title:'JRPG Piano', author:'Joth', playback:'rendered',
  ambient:false, duration, musicDuration:duration, sections, events:[], visuals,
  timing:'从原曲中高频起音强度提取显著琴音，非完整旋律转谱'};
const track = {duration, sampleRate:44100,
  sha256:crypto.createHash('sha256').update(bytes).digest('hex'), base64:bytes.toString('base64')};
fs.writeFileSync(path.join(root,'assets/jrpg-track.js'),
  '// Generated by scripts/build-jrpg-track.cjs. JRPG Piano by Joth, CC0; see JRPG-PIANO-LICENSE.md.\n'+
  'globalThis.cityScore = '+JSON.stringify(score)+';\n'+
  'globalThis.cityMusicTrack = '+JSON.stringify(track)+';\n');
process.stdout.write(JSON.stringify({duration, count:visuals.length, times:visuals.map(n=>+n.at.toFixed(3)),
  peak:raw.reduce((peak, value) => Math.max(peak, Math.abs(value)), 0), sha256:track.sha256})+'\n');
