// 确定性打包：把指定目录中九个原始 MP3 编成普通本地脚本，不重编码音频。
// 用法：node scripts/build-piano-samples.cjs /absolute/path/to/downloaded-samples
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const input = process.argv[2];
if (!input || !path.isAbsolute(input)) {
  throw new Error("请提供九个钢琴 MP3 所在文件夹的绝对路径。");
}

const notes = [
  [42, "Fs2.mp3", 102320],
  [45, "A2.mp3", 81678],
  [48, "C3.mp3", 78036],
  [54, "Fs3.mp3", 77933],
  [60, "C4.mp3", 78718],
  [66, "Fs4.mp3", 68219],
  [72, "C5.mp3", 68920],
  [78, "Fs5.mp3", 51597],
  [81, "A5.mp3", 45747],
];

const samples = notes.map(([midi, file, expectedBytes]) => {
  const data = fs.readFileSync(path.join(input, file));
  if (data.length !== expectedBytes) {
    throw new Error(`${file} 文件大小不符：预期 ${expectedBytes}，实际 ${data.length}。`);
  }
  return {
    midi, file, bytes: data.length,
    source: `https://tonejs.github.io/audio/salamander/${file}`,
    sha256: crypto.createHash("sha256").update(data).digest("hex"),
    base64: data.toString("base64"),
  };
});

const output = path.resolve(__dirname, "../assets/piano-samples.js");
const header = "/* Generated by scripts/build-piano-samples.cjs.\n" +
  " * Salamander Grand Piano — Alexander Holm — CC BY 3.0.\n" +
  " * https://creativecommons.org/licenses/by/3.0/\n" +
  " * Original MP3 bytes, Base64 encoding only. See PIANO-LICENSE.md.\n" +
  " */\n";
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, header + "globalThis.cityPianoSamples = " +
  JSON.stringify(samples, null, 2) + ";\n");
process.stdout.write(`已生成 ${output}；${samples.length} 个单音，原始音频 ${samples.reduce((sum, item) => sum + item.bytes, 0)} 字节。\n`);
